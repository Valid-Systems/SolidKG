function normalizedPath(filePath: string): string {
  return filePath.replace(/\\/g, "/").toLowerCase();
}

function basename(filePath: string): string {
  const parts = normalizedPath(filePath).split("/").filter(Boolean);
  return parts[parts.length - 1] ?? "";
}

export function isGeneratedFile(filePath: string): boolean {
  const normalized = normalizedPath(filePath);
  const parts = normalized.split("/").filter(Boolean);
  if (
    parts.some(
      (part) =>
        part === "__generated__" ||
        part === "generated" ||
        part === "autogenerated",
    )
  ) {
    return true;
  }

  const name = basename(filePath);
  return (
    /(^|[._-])(generated|autogenerated|gen)([._-]|$)/.test(name) ||
    /[._-]pb\.[a-z0-9]+$/.test(name) ||
    /_pb2(_grpc)?\.py$/.test(name) ||
    /[._-]grpc[._-]pb\.[a-z0-9]+$/.test(name) ||
    /\.g\.[a-z0-9]+$/.test(name) ||
    /\.designer\.[a-z0-9]+$/.test(name)
  );
}

export function isGeneratedFileQuery(query: string): boolean {
  const normalized = normalizedPath(query);
  return (
    /\b(generated|autogenerated|protobuf|proto|grpc|pb2)\b/i.test(normalized) ||
    /[._-]pb\.[a-z0-9]+\b/.test(normalized) ||
    /_pb2(_grpc)?\.py\b/.test(normalized) ||
    /[._-]grpc[._-]pb\.[a-z0-9]+\b/.test(normalized) ||
    /\.g\.[a-z0-9]+\b/.test(normalized) ||
    /\.designer\.[a-z0-9]+\b/.test(normalized)
  );
}
